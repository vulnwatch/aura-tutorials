async function findVideo(id, dirs) {
  for (const dir of dirs) {
    for (const path of [join(dir, `${id}.mp4`), join(dir, id, `${id}.mp4`)]) {
      if (await stat(path).catch(() => null)) return path;
    }
  }
  throw new Error(`site: no video of ${id} in ${dirs.join(", ")}; render it, or download the latest release`);
}

async function build([out, ...videoDirs]) {
  if (!out || videoDirs.length === 0) throw new Error("build: takes the output directory and the directories of the videos");
  const site = await loadSite();
  await rm(out, { recursive: true, force: true });
  for (const dir of ["assets", "videos"]) await mkdir(join(out, dir), { recursive: true });

  await copyFile("node_modules/@fontsource-variable/inter/files/inter-latin-wght-normal.woff2", join(out, "assets", "inter.woff2"));
  await copyFile("aura/src/favicon.svg", join(out, "assets", "mark.svg"));
  await writeFile(join(out, "assets", "site.css"), CSS);
  await writeFile(join(out, "assets", "site.js"), JS);

  for (const tutorial of site.tutorials) {
    const video = await findVideo(tutorial.id, videoDirs);
    await copyFile(video, join(out, "videos", `${tutorial.id}.mp4`));
    // The subtitles of the video, the narration that its voice reads, which a
    // video rendered before the narration lacks.
    const subtitles = video.replace(/\.mp4$/, ".vtt");
    tutorial.subtitles = Boolean(await stat(subtitles).catch(() => null));
    if (tutorial.subtitles) await copyFile(subtitles, join(out, "videos", `${tutorial.id}.vtt`));
    await execFileAsync("ffmpeg", [
      "-hide_banner", "-loglevel", "error", "-y",
      "-ss", String(POSTER_AT), "-i", video, "-frames:v", "1", "-update", "1",
      "-vf", "scale=1280:-2", "-q:v", "4", join(out, "videos", `${tutorial.id}.jpg`),
    ]);
    await writeFile(join(out, "videos", `${tutorial.id}.chapters.vtt`), chaptersVtt(tutorial));
    await mkdir(join(out, "tutorials", tutorial.id), { recursive: true });
    await writeFile(join(out, "tutorials", tutorial.id, "index.html"), tutorialPage(tutorial));
  }
  await writeFile(join(out, "index.html"), homePage(site));
  console.error(`site: ${site.tutorials.length} tutorial(s) in ${out}`);
}

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".svg": "image/svg+xml",
  ".jpg": "image/jpeg",
  ".woff2": "font/woff2",
  ".vtt": "text/vtt; charset=utf-8",
  ".mp4": "video/mp4",
};

async function serve([dir, port]) {
  if (!dir || !port) throw new Error("serve: takes the directory of the site and a port");
  const base = resolve(dir);
  createServer(async (request, response) => {
    const path = decodeURIComponent(new URL(request.url, "http://localhost").pathname);
    let file = normalize(join(base, path));
    if (file !== base && !file.startsWith(base + sep)) {
      response.writeHead(403).end();
      return;
    }
    let info = await stat(file).catch(() => null);
    if (info?.isDirectory()) {
      file = join(file, "index.html");
      info = await stat(file).catch(() => null);
    }
    if (!info?.isFile()) {
      response.writeHead(404, { "content-type": "text/plain" }).end("Not found");
      return;
    }
    const headers = { "content-type": TYPES[extname(file)] ?? "application/octet-stream", "accept-ranges": "bytes" };
    const range = /^bytes=(\d*)-(\d*)$/.exec(request.headers.range ?? "");
    if (range && (range[1] || range[2])) {
      const start = range[1] ? Number(range[1]) : Math.max(0, info.size - Number(range[2]));
      const end = range[1] && range[2] ? Math.min(Number(range[2]), info.size - 1) : info.size - 1;
      if (start > end) {
        response.writeHead(416, { "content-range": `bytes */${info.size}` }).end();
        return;
      }
      response.writeHead(206, { ...headers, "content-range": `bytes ${start}-${end}/${info.size}`, "content-length": end - start + 1 });
      createReadStream(file, { start, end }).pipe(response);
      return;
    }
    response.writeHead(200, { ...headers, "content-length": info.size });
    createReadStream(file).pipe(response);
  }).listen(Number(port), "0.0.0.0", () => console.error(`site: serving ${dir} on port ${port}`));
}

const [command, ...args] = process.argv.slice(2);
const commands = { build, serve };
if (!commands[command]) {
  console.error("usage: node src/site.mjs build <out> <videos>... | serve <dir> <port>");
  process.exit(2);
}
try {
  await commands[command](args);
} catch (error) {
  console.error(error.message);
  process.exit(1);
}
